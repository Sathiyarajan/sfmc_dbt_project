-- =====================================================================
-- 01_databases_roles_warehouses.sql
-- Run once as ACCOUNTADMIN (or a role with CREATE DATABASE/WAREHOUSE/ROLE)
-- Creates DEV / UAT / PROD isolation for the SFMC email analytics project
-- =====================================================================

-- ---------- Warehouses (one per env, auto-suspend to control cost) ----------
CREATE WAREHOUSE IF NOT EXISTS SFMC_WH_DEV
  WITH WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE WAREHOUSE IF NOT EXISTS SFMC_WH_UAT
  WITH WAREHOUSE_SIZE = 'SMALL' AUTO_SUSPEND = 120 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE WAREHOUSE IF NOT EXISTS SFMC_WH_PROD
  WITH WAREHOUSE_SIZE = 'MEDIUM' AUTO_SUSPEND = 300 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

-- ---------- Databases (bronze/silver/gold live as SCHEMAS inside each) ----------
CREATE DATABASE IF NOT EXISTS SFMC_DEV;
CREATE DATABASE IF NOT EXISTS SFMC_UAT;
CREATE DATABASE IF NOT EXISTS SFMC_PROD;
CREATE DATABASE IF NOT EXISTS SFMC_RAW_DEV;   -- landing zone databases (S3 stage targets)
CREATE DATABASE IF NOT EXISTS SFMC_RAW_UAT;
CREATE DATABASE IF NOT EXISTS SFMC_RAW_PROD;

-- ---------- Schemas: bronze / silver / silver_snapshots / gold per env ----------
CREATE SCHEMA IF NOT EXISTS SFMC_DEV.BRONZE;
CREATE SCHEMA IF NOT EXISTS SFMC_DEV.SILVER;
CREATE SCHEMA IF NOT EXISTS SFMC_DEV.SILVER_SNAPSHOTS;
CREATE SCHEMA IF NOT EXISTS SFMC_DEV.GOLD;

CREATE SCHEMA IF NOT EXISTS SFMC_UAT.BRONZE;
CREATE SCHEMA IF NOT EXISTS SFMC_UAT.SILVER;
CREATE SCHEMA IF NOT EXISTS SFMC_UAT.SILVER_SNAPSHOTS;
CREATE SCHEMA IF NOT EXISTS SFMC_UAT.GOLD;

CREATE SCHEMA IF NOT EXISTS SFMC_PROD.BRONZE;
CREATE SCHEMA IF NOT EXISTS SFMC_PROD.SILVER;
CREATE SCHEMA IF NOT EXISTS SFMC_PROD.SILVER_SNAPSHOTS;
CREATE SCHEMA IF NOT EXISTS SFMC_PROD.GOLD;

-- ---------- Roles ----------
CREATE ROLE IF NOT EXISTS SFMC_DBT_DEV_ROLE;
CREATE ROLE IF NOT EXISTS SFMC_DBT_UAT_ROLE;
CREATE ROLE IF NOT EXISTS SFMC_DBT_PROD_ROLE;

GRANT USAGE ON WAREHOUSE SFMC_WH_DEV  TO ROLE SFMC_DBT_DEV_ROLE;
GRANT USAGE ON WAREHOUSE SFMC_WH_UAT  TO ROLE SFMC_DBT_UAT_ROLE;
GRANT USAGE ON WAREHOUSE SFMC_WH_PROD TO ROLE SFMC_DBT_PROD_ROLE;

GRANT ALL ON DATABASE SFMC_DEV      TO ROLE SFMC_DBT_DEV_ROLE;
GRANT ALL ON DATABASE SFMC_RAW_DEV  TO ROLE SFMC_DBT_DEV_ROLE;
GRANT ALL ON DATABASE SFMC_UAT      TO ROLE SFMC_DBT_UAT_ROLE;
GRANT ALL ON DATABASE SFMC_RAW_UAT  TO ROLE SFMC_DBT_UAT_ROLE;
GRANT ALL ON DATABASE SFMC_PROD     TO ROLE SFMC_DBT_PROD_ROLE;
GRANT ALL ON DATABASE SFMC_RAW_PROD TO ROLE SFMC_DBT_PROD_ROLE;

GRANT ALL ON ALL SCHEMAS IN DATABASE SFMC_DEV  TO ROLE SFMC_DBT_DEV_ROLE;
GRANT ALL ON ALL SCHEMAS IN DATABASE SFMC_UAT  TO ROLE SFMC_DBT_UAT_ROLE;
GRANT ALL ON ALL SCHEMAS IN DATABASE SFMC_PROD TO ROLE SFMC_DBT_PROD_ROLE;

GRANT ALL ON FUTURE SCHEMAS IN DATABASE SFMC_DEV TO ROLE SFMC_DBT_DEV_ROLE;

